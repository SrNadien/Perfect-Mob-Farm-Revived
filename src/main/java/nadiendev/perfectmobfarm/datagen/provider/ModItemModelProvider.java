package nadiendev.perfectmobfarm.datagen.provider;

import nadiendev.perfectmobfarm.PerfectMobFarm;
import nadiendev.perfectmobfarm.block.FarmTier;
import net.minecraft.data.PackOutput;
import net.minecraft.resources.ResourceLocation;
import net.neoforged.neoforge.client.model.generators.ItemModelBuilder;
import net.neoforged.neoforge.client.model.generators.ItemModelProvider;
import net.neoforged.neoforge.client.model.generators.ModelFile;
import net.neoforged.neoforge.common.data.ExistingFileHelper;

import java.util.List;

/**
 * Generates the item models of the mob shards, the farm upgrades and the mob farm block items.
 * The block models themselves come from {@link ModBlockStateProvider}.
 */
public class ModItemModelProvider extends ItemModelProvider {

    /** Item property (registered client side) that is 1.0 when a shard has killed enough mobs */
    private static final ResourceLocation COMPLETED = PerfectMobFarm.id("completed");

    /** Registry names of the shards. Each one has a {@code <name>_completed} model with its own texture */
    private static final List<String> SHARDS = List.of("mob_shard", "advanced_mob_shard", "ultimate_mob_shard");

    public ModItemModelProvider(PackOutput output, ExistingFileHelper existingFileHelper) {
        super(output, PerfectMobFarm.MODID, existingFileHelper);
    }

    @Override
    protected void registerModels() {
        for (String shard : SHARDS) {
            shardModel(shard);
        }
        generated("speed_upgrade");
        generated("mob_slot_upgrade");
        for (FarmTier tier : FarmTier.values()) {
            farmItemModel(tier.getName() + "_mob_farm");
            farmItemModel(tier.getName() + "_energy_mob_farm");
        }
    }

    /**
     * The block model is generated by ModBlockStateProvider, so it is referenced without an existence check
     */
    private void farmItemModel(String name) {
        getBuilder(name).parent(new ModelFile.UncheckedModelFile(modLoc("block/" + name)));
    }

    /**
     * A shard uses its completed model while the {@code completed} property is 1.0
     */
    private void shardModel(String name) {
        ItemModelBuilder completed = generated(name + "_completed");
        generated(name)
                .override()
                .predicate(COMPLETED, 1.0F)
                .model(completed)
                .end();
    }

    private ItemModelBuilder generated(String name) {
        return getBuilder(name)
                .parent(new ModelFile.UncheckedModelFile("item/generated"))
                .texture("layer0", modLoc("item/" + name));
    }
}
